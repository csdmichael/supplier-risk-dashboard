"""Service layer for the generated project."""
from typing import List, Optional

from fastapi import FastAPI, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware

from .models import Dashboard, DashboardCreate, DashboardUpdate
from .store import store

app = FastAPI(
    title="Supplier Risk Dashboard API",
    version="0.1.0",
    description="REST API for Supplier Risk Dashboard. Generated by the Agentic SDLC workflow.",
    docs_url="/docs",
    openapi_url="/openapi.json",
    openapi_tags=[
        {"name": "health", "description": "Liveness probe used by the deploy pipeline."},
        {"name": "dashboards", "description": "Dashboards managed by this service."},
    ],
)

# The UI is a separate App Service, so it is a cross-origin caller.
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)


@app.get("/health", tags=["health"])
def health() -> dict:
    return {"status": "ok"}


@app.get("/api/dashboards", response_model=List[Dashboard], tags=["dashboards"])
def list_items(status: Optional[str] = Query(default=None)) -> List[dict]:
    return store.list(status)


@app.post("/api/dashboards", response_model=Dashboard, status_code=201, tags=["dashboards"])
def create_item(body: DashboardCreate) -> dict:
    return store.create(body.model_dump())


@app.get("/api/dashboards/{item_id}", response_model=Dashboard, tags=["dashboards"])
def get_item(item_id: int) -> dict:
    item = store.get(item_id)
    if item is None:
        raise HTTPException(status_code=404, detail="Dashboard not found")
    return item


@app.patch("/api/dashboards/{item_id}", response_model=Dashboard, tags=["dashboards"])
def update_item(item_id: int, body: DashboardUpdate) -> dict:
    item = store.update(item_id, body.model_dump())
    if item is None:
        raise HTTPException(status_code=404, detail="Dashboard not found")
    return item


@app.delete("/api/dashboards/{item_id}", status_code=204, tags=["dashboards"])
def delete_item(item_id: int) -> None:
    if not store.delete(item_id):
        raise HTTPException(status_code=404, detail="Dashboard not found")
